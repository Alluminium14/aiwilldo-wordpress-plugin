<script>
(function(){
  const page = document.querySelector('.wtg-page');
  if(!page) return;

  /* Sticky navigation */
  const nav = document.getElementById('wtgNav');
  const onScroll = () => nav.classList.toggle('is-scrolled', window.scrollY > 24);
  onScroll();
  window.addEventListener('scroll', onScroll, {passive:true});

  /* Mobile menu */
  const menuBtn = document.getElementById('wtgMenuBtn');
  const navLinks = document.getElementById('wtgNavLinks');
  menuBtn.addEventListener('click', () => {
    navLinks.classList.toggle('is-open');
    document.body.classList.toggle('wtg-menu-open', navLinks.classList.contains('is-open'));
  });
  navLinks.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
    navLinks.classList.remove('is-open');
    document.body.classList.remove('wtg-menu-open');
  }));

  /* Hero slider */
  const slides = [...document.querySelectorAll('.wtg-slide')];
  const dots = [...document.querySelectorAll('.wtg-dot')];
  let current = 0;
  let timer;

  function activateSlide(index){
    current = index;
    slides.forEach((el,i)=>el.classList.toggle('is-active',i===index));
    dots.forEach((el,i)=>{
      el.classList.remove('is-active');
      void el.offsetWidth;
      if(i===index) el.classList.add('is-active');
    });
  }
  function startSlider(){
    clearInterval(timer);
    timer = setInterval(()=>activateSlide((current+1)%slides.length),6000);
  }
  dots.forEach((dot,i)=>dot.addEventListener('click',()=>{activateSlide(i);startSlider()}));
  activateSlide(0);
  startSlider();

  /* Scroll reveal */
  const revealItems = document.querySelectorAll('[data-wtg-reveal]');
  if('IntersectionObserver' in window){
    const observer = new IntersectionObserver(entries=>{
      entries.forEach(entry=>{
        if(entry.isIntersecting){
          entry.target.classList.add('is-visible');
          observer.unobserve(entry.target);
        }
      });
    },{threshold:.12});
    revealItems.forEach(el=>observer.observe(el));
  } else {
    revealItems.forEach(el=>el.classList.add('is-visible'));
  }

  /* FAQ */
  document.querySelectorAll('.wtg-faq-q').forEach(btn=>{
    btn.addEventListener('click',()=>btn.closest('.wtg-faq-item').classList.toggle('is-open'));
  });

  /* Demo form status after the server processes a submission. */
  const demoForm = document.getElementById('wtgDemoForm');
  const formMessage = document.getElementById('wtgFormMessage');
  const formStatus = new URLSearchParams(window.location.search).get('awd_form');
  if (demoForm && formMessage && formStatus && formMessage.dataset[formStatus]) {
    formMessage.textContent = formMessage.dataset[formStatus];
    formMessage.style.display = 'block';
  }
})();
</script>
